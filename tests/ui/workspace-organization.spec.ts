test("legacy configurable stream lanes immediately follow Planning attention, followed by stream management", async ({ page, assignment }) => {
  await page.goto("/");
  const board = page.locator("#sequencing-board");
  const attention = board.locator(".action-center");
  await expect(board.locator("#project-streams > .stream-lane")).toHaveCount(2);
  await expect(attention).toHaveAttribute("open", "");
  await expect(attention.getByRole("button").first()).toBeVisible();
  await attention.locator("summary").click();
  await expect(attention).not.toHaveAttribute("open", "");
  await expect(attention.locator("#next-actions-title")).toBeVisible();
  await expect(attention.locator(".action-center-status")).toContainText(/\d+ open/);
  await expect(attention.getByText("Expand", { exact: true })).toBeVisible();
  await expect(attention.locator(".action-item").first()).toBeHidden();
  await attention.locator("summary").click();
  await expect(attention).toHaveAttribute("open", "");
  await expect(attention.getByText("Minimize", { exact: true })).toBeVisible();
  await expect(attention.locator(".action-item").first()).toBeVisible();
  expect(await attention.evaluate((element) => element.nextElementSibling?.id)).toBe("project-streams");
  expect(await board.locator("#project-streams").evaluate((element) => element.nextElementSibling?.classList.contains("stream-manager"))).toBe(true);
  await expect(board.getByRole("heading", { name: "Outcome delivery" })).toHaveCount(0);
  const manager = board.locator(".stream-manager");
  await manager.locator("summary").first().click();
  await expect(manager).toContainText("Each stream runs one project at a time");
  await expect(manager.getByLabel("WIP limit")).toHaveCount(0);
  await manager.getByLabel("Name", { exact: true }).fill("New focus");
  await manager.getByRole("button", { name: "Add at 0%" }).click();
  await expect(board.locator("#project-streams > .stream-lane")).toHaveCount(3);
  await expect(board.getByRole("heading", { name: "New focus", exact: true })).toBeVisible();
  await expect(board.locator("#project-streams")).toContainText("1 project at a time");
  expect((await assignment.board()).streams).toHaveLength(3);
  expect(await board.locator("#project-streams").evaluate((element) => element.nextElementSibling?.classList.contains("stream-manager"))).toBe(true);
});

test("Outcome catalog combines editing, deletion and fresh compact forecast health", async ({ page, assignment }) => {
  await page.goto("/");
  await page.getByRole("button", { name: /^Outcomes/ }).click();
  const catalog = page.locator("#outcome-catalog");
  await expect(page.locator("#outcome-delivery")).toHaveCount(0);
  const initialDate = (await assignment.board()).forecast.outcomes[0].endDate!;
  const launch = catalog.locator(".catalog-row").filter({ has: page.getByRole("button", { name: "Launch", exact: true }) });
  await expect(launch.locator(".catalog-health")).toContainText(initialDate);
  await launch.getByRole("button", { name: "Launch", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "Launch", exact: true })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await launch.getByRole("button", { name: "Launch", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Edit details", exact: true }).click();
  await expect(page.getByLabel("Outcome title", { exact: true }).filter({ visible: true })).toBeFocused();
  const editor = page.getByRole("dialog");
  await editor.getByLabel("Outcome title").fill("Launch readiness");
  await editor.getByRole("button", { name: "Save details", exact: true }).click();
  await expect(catalog).toContainText("Launch readiness");
  await editor.getByRole("button", { name: "Close outcome" }).click();
  await expect(page.locator(".catalog-list").getByRole("button", { name: "Launch readiness", exact: true })).toBeVisible();
  await page.getByRole("button", { name: /^Board/ }).click();
  await page.locator("#stream-work-core > summary").click();
  await page.getByRole("button", { name: "Move Web experience up", exact: true }).click();
  await expect(page.locator("#sequencing-board").getByRole("status")).toContainText("Web experience moved");
  await page.getByRole("button", { name: /^Outcomes/ }).click();
  const changedDate = (await assignment.board()).forecast.outcomes[0].endDate!;
  expect(changedDate).not.toBe(initialDate);
  const renamed = catalog.locator(".catalog-row").filter({ has: page.getByRole("button", { name: "Launch readiness", exact: true }) });
  await expect(renamed.locator(".catalog-health")).toContainText(changedDate);
  page.once("dialog", (dialog) => void dialog.accept());
  await renamed.getByRole("button", { name: "Launch readiness", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Delete outcome", exact: true }).click();
  await expect(page.locator("#outcome-catalog")).toContainText("No outcomes yet");
});

test("new outcomes and their project links are created together in the outcome sidebar", async ({ page, assignment }) => {
  await page.goto("/");
  await page.getByRole("button", { name: /^Outcomes/ }).click();
  const catalog = page.locator("#outcome-catalog");
  await page.locator(".view-heading").getByRole("button", { name: "Add outcome", exact: true }).click();
  const modal = page.getByRole("dialog");
  await expect(modal).toBeVisible();
  await modal.getByLabel("Outcome title", { exact: true }).fill("Onboarding complete");
  await modal.getByRole("button", { name: "Projects", exact: true }).click();
  const apiFoundation = modal.getByRole("checkbox", { name: /API foundation/ });
  await apiFoundation.check();
  await expect(apiFoundation).toBeChecked();
  await modal.getByLabel("API foundation requirement").selectOption("optional");
  await modal.getByRole("button", { name: "Create outcome", exact: true }).click();
  await expect(modal.locator("h2")).toHaveText("Onboarding complete");
  await modal.getByRole("button", { name: "Close outcome" }).click();
  const outcome = catalog.locator(".catalog-row").filter({ has: page.getByRole("button", { name: "Onboarding complete", exact: true }) });
  await expect(outcome).toContainText("0 required · 1 optional");
  await outcome.getByRole("button", { name: "Onboarding complete", exact: true }).click();
  await modal.getByRole("button", { name: "Projects", exact: true }).click();
  await expect(modal).toContainText("API foundation");
  const board = await assignment.board();
  const created = board.outcomes.find((item) => item.title === "Onboarding complete");
  expect(created).toBeTruthy();
  expect(board.links).toContainEqual({ outcome_id: created!.id, project_id: "a", requirement: "optional" });
});

